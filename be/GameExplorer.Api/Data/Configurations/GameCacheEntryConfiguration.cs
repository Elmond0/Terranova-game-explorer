using GameExplorer.Api.Data.Entities;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace GameExplorer.Api.Data.Configurations;

public class GameCacheEntryConfiguration : IEntityTypeConfiguration<GameCacheEntry>
{
	public void Configure(EntityTypeBuilder<GameCacheEntry> builder)
	{
		// Column names are snake_case (UseSnakeCaseNamingConvention)
		builder.ToTable("game_cache", table =>
		{
			table.HasCheckConstraint("ck_game_cache_rating", "rating BETWEEN 0 AND 5");
			table.HasCheckConstraint("ck_game_cache_metacritic", "metacritic BETWEEN 0 AND 100");
		});

		builder.HasKey(g => g.RawgId);
		builder.Property(g => g.RawgId).ValueGeneratedNever(); // RAWG id, not generated by us

		builder.HasIndex(g => g.Slug).IsUnique();
		builder.Property(g => g.Details).HasColumnType("jsonb");
	}
}
